"""End-to-end pipeline: Parquet -> cleaned aggregate (DuckDB) -> difference-in-differences -> figures ->
Excel, Tableau and docs.

Usage:
    python -m src.run_pipeline                  # full run (about 5 minutes on a laptop)
    python -m src.run_pipeline --skip-build     # reuse the existing warehouse
    python -m src.run_pipeline --analysis-only  # skip Excel, Tableau and README rendering
"""
from __future__ import annotations

import argparse
import json
from datetime import datetime, timezone

import numpy as np
import pandas as pd

from src import config, data, did, figures


def records(df: pd.DataFrame) -> list[dict]:
    out = []
    for rec in df.to_dict(orient="records"):
        clean = {}
        for k, v in rec.items():
            if isinstance(v, (pd.Timestamp, datetime)):
                clean[k] = v.strftime("%Y-%m-%d")
            elif hasattr(v, "isoformat") and not isinstance(v, str):
                clean[k] = v.isoformat()
            elif isinstance(v, (np.floating, float)):
                clean[k] = None if np.isnan(v) else float(v)
            elif isinstance(v, np.integer):
                clean[k] = int(v)
            elif isinstance(v, np.bool_):
                clean[k] = bool(v)
            else:
                clean[k] = v
        out.append(clean)
    return out


def write_quality_log(checks: pd.DataFrame, counts: dict) -> None:
    rules = ["outside_window", "duration_out_of_range", "distance_out_of_range", "speed_out_of_range",
             "unknown_zone", "non_positive_fare"]
    text = {"outside_window": "Pickup outside Oct-Mar 2023-24 and Oct-Mar 2024-25",
            "duration_out_of_range": "Duration under 1 minute or over 3 hours",
            "distance_out_of_range": "Distance zero, missing or over 100 miles",
            "speed_out_of_range": "Speed under 0.5 or over 65 mph",
            "unknown_zone": "Pickup or dropoff zone unknown (264, 265) or missing",
            "non_positive_fare": "Base fare or rider total zero or negative"}
    lines = ["# Data quality log", "",
             "Generated by `src/run_pipeline.py` from `sql/03_quality_checks.sql`. A trip is kept only if it passes "
             "every rule; a trip can break several rules, so the rule counts overlap.", ""]
    for service, g in checks.groupby("service"):
        tot = g[["rows_read", *rules, "rows_kept"]].sum()
        lines += [f"## {service}", "", "| Rule | Trips | Share of rows read |", "|---|---:|---:|"]
        lines += [f"| {text[r]} | {int(tot[r]):,} | {tot[r] / tot.rows_read:.2%} |" for r in rules]
        lines += [f"| **Kept** | **{int(tot.rows_kept):,}** | **{tot.rows_kept / tot.rows_read:.2%}** |", "",
                  "| Pickup month | Rows read | Kept |", "|---|---:|---:|"]
        main = g[g.rows_read >= 1000]
        stray = g[g.rows_read < 1000]
        lines += [f"| {r.pickup_month} | {int(r.rows_read):,} | {int(r.rows_kept):,} |" for r in main.itertuples()]
        if len(stray):
            lines.append(f"| other months (stray timestamps, {len(stray)} months) | {int(stray.rows_read.sum()):,} | "
                         f"{int(stray.rows_kept.sum()):,} |")
        lines.append("")
    lines += ["## Warehouse", "", "| Item | Count |", "|---|---:|"] + [f"| {k} | {v:,} |" for k, v in counts.items()]
    (config.ROOT / "docs" / "data_quality_log.md").write_text("\n".join(lines) + "\n")


def main(skip_build: bool = False, analysis_only: bool = False) -> dict:
    for folder in (config.FIGURES, config.TABLES, config.TABLEAU_DATA):
        folder.mkdir(parents=True, exist_ok=True)
    if skip_build and config.DB_PATH.exists():
        checks = pd.read_csv(config.TABLES / "quality_checks.csv")
    else:
        checks = data.build_warehouse()
        checks.to_csv(config.TABLES / "quality_checks.csv", index=False)
    counts = data.row_counts()
    write_quality_log(checks, counts)
    print("warehouse ready", flush=True)

    flow_week = data.query("05_flow_week.sql")
    group_day = data.query("06_group_day.sql")
    hour_weekday = data.query("07_hour_weekday.sql")
    zone_period = data.query("08_zone_period.sql")
    unit = data.query("09_unit_economics.sql")
    zones = data.table("zones")

    # ---- difference-in-differences per service (year-over-year design; see src/did.py)
    est, events, weekly = {}, {}, {}
    no_thanksgiving = [w for w in range(config.REL_WEEKS[0], config.REL_WEEKS[1] + 1) if w not in config.THANKSGIVING_WEEKS]
    for service in config.SERVICES:
        panel = did.yoy_panel(flow_week, service)
        es, pretest = did.event_study(panel)
        events[service] = es
        weekly[service] = did.speed_by_week(group_day, service)
        main_panel = did.yoy_panel(flow_week, service, weeks=no_thanksgiving)
        est[service] = {
            "trips": did.trips_did(main_panel),
            "trips_all_weeks": did.trips_did(panel)["pooled"],
            "trips_unweighted": did.trips_did(main_panel, weights=False)["pooled"],
            "placebo": did.placebo(flow_week, service),
            "single_season": did.single_season(flow_week, service),
            "pre_trend_test": pretest,
            "money": did.money_did(main_panel),
            "speed": did.speed_did(group_day, service),
            "speed_into_vs_elsewhere": did.speed_did(group_day, service, treated="Into zone", control="Elsewhere"),
        }
        m, t = est[service]["money"].get("passenger_cost_per_trip"), est[service]["trips"]["pooled"]
        if m:
            pct_price = m["coef"] / m["treated_pre_mean_s1"]
            est[service]["price_change_pct"] = float(pct_price)
            est[service]["implied_price_elasticity"] = float(t["coef"] / pct_price) if abs(pct_price) > 1e-6 else None
        print(f"DiD done: {service}", flush=True)

    summary = did.group_period_summary(group_day)
    s1_post = group_day[(group_day.season == config.TOLL_SEASON) & group_day.post]
    fee_share = (s1_post.groupby(["service", "trip_group"])
                 .apply(lambda x: np.average(x.share_with_cbd_fee, weights=x.trips), include_groups=False)
                 .rename("share_with_cbd_fee").reset_index())
    zchange = figures.zone_change_table(zone_period)
    heat = figures.speed_heatmap_table(hour_weekday)
    peak = (heat.dow.between(1, 5) & heat.pickup_hour.between(5, 20)) | (heat.dow.isin([0, 6]) & heat.pickup_hour.between(9, 20))
    speed_periods = {"toll_peak_hours_pts": float(heat.loc[peak, "relative_change_net"].mean()),
                     "overnight_hours_pts": float(heat.loc[~peak, "relative_change_net"].mean())}

    # ---- business overview
    gd = group_day.assign(period=np.where(group_day.post, "after", "before"))
    totals = (gd.groupby(["season", "service", "period"])
              .agg(trips=("trips", "sum"), days=("pickup_date", "nunique")).reset_index())
    totals["trips_per_day"] = totals.trips / totals.days
    s1 = group_day[(group_day.season == config.TOLL_SEASON) & ~group_day.post]
    touching = (s1[s1.trip_group.isin(config.TREATED_GROUPS)].groupby("service").trips.sum()
                / s1.groupby("service").trips.sum())
    business = {
        "clean_trips": counts["clean_trips"], "rows_read": int(checks.rows_read.sum()),
        "rows_kept": int(checks.rows_kept.sum()), "cbd_zones": counts["cbd_zones"],
        "trips_per_day": records(totals),
        "share_touching_zone_before": {s: float(touching[s]) for s in config.SERVICES},
    }

    # ---- tables
    es_all = pd.concat([e.assign(service=s) for s, e in events.items()])
    wk_all = pd.concat([w.assign(service=s) for s, w in weekly.items()])
    tables = {"group_period_summary": summary, "event_study_trips": es_all, "speed_gap_by_week": wk_all,
              "unit_economics": unit, "zone_change": zchange, "speed_by_hour_weekday": heat,
              "cbd_fee_share_after": fee_share}
    for name, t in tables.items():
        t.to_csv(config.TABLES / f"{name}.csv", index=False)

    shapes = None
    try:
        from src import zones as zgeo
        shapes = zgeo.zone_shapes()
    except Exception as exc:                       # geopandas missing: skip the map, keep everything else
        print(f"zone map skipped: {exc}")
    figs = [figures.daily_trips(group_day), figures.event_study(events)]
    if shapes is not None:
        figs.append(figures.zone_map(zchange, shapes))
    figs += [figures.speed_heatmap(heat), figures.speed_by_week(weekly), figures.price_breakdown(unit)]

    results = {
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "settings": {"seasons": config.SEASONS, "toll_start": config.TOLL_START, "rel_weeks": config.REL_WEEKS,
                     "placebo_rel_week": config.PLACEBO_REL_WEEK, "min_weekly_trips": config.MIN_WEEKLY_TRIPS,
                     "thanksgiving_weeks": config.THANKSGIVING_WEEKS, "holiday_weeks": config.HOLIDAY_WEEKS,
                     "charges": config.SERVICES},
        "row_counts": counts, "business": business, "estimates": est,
        "group_period_summary": records(summary), "unit_economics": records(unit),
        "cbd_fee_share_after": records(fee_share), "mta_vehicle_reduction": config.MTA_VEHICLE_REDUCTION,
        "speed_by_toll_period": speed_periods,
        "figures": figs,
    }
    config.RESULTS_JSON.write_text(json.dumps(results, indent=2, default=str))

    if not analysis_only:
        from src import excel_model, report, tableau_workbook
        cent = None
        try:
            from src import zones as zgeo
            cent = zgeo.centroids()
        except Exception as exc:
            print(f"centroids skipped: {exc}")
        results["tableau"] = tableau_workbook.build(zchange, heat, es_all, group_day, unit, cent)
        results["excel"] = excel_model.build(results)
        report.render(results)
        config.RESULTS_JSON.write_text(json.dumps(results, indent=2, default=str))
    t = est["Uber/Lyft"]["trips"]["pooled"]
    print(f"Pipeline finished: Uber/Lyft trips touching the zone {t['effect_pct'] * 100:+.1f}% "
          f"(95% CI {t['effect_pct_low'] * 100:+.1f}% to {t['effect_pct_high'] * 100:+.1f}%)")
    return results


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--skip-build", action="store_true")
    parser.add_argument("--analysis-only", action="store_true")
    a = parser.parse_args()
    main(skip_build=a.skip_build, analysis_only=a.analysis_only)
